#!/usr/bin/env python3
"""Regenerate the emoji catalog data table from the vendored Noto manifest.

Reads ui/assets/emoji/noto_manifest.json (a snapshot of the upstream
noto-emoji-animation api.json, CC BY 4.0) and writes the C++ implementation
unit src/application/emoji/emoji_catalog_data.cpp.

Usage:
    python3 tools/generate_emoji_catalog.py [manifest] [output]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

CATEGORY_MAP = {
    "Smileys and emotions": "Smileys",
    "People": "People",
    "Animals and nature": "Animals",
    "Food and drink": "Food",
    "Activities and events": "Activities",
    "Travel and places": "Travel",
    "Objects": "Objects",
    "Symbols": "Symbols",
    "Flags": "Flags",
}

CATEGORY_ORDER = [
    "Smileys",
    "People",
    "Animals",
    "Food",
    "Activities",
    "Travel",
    "Objects",
    "Symbols",
    "Flags",
]


def utf8_bytes(code_point: int) -> bytes:
    if code_point <= 0x7F:
        return bytes([code_point])
    if code_point <= 0x7FF:
        return bytes([
            0xC0 | (code_point >> 6),
            0x80 | (code_point & 0x3F),
        ])
    if code_point <= 0xFFFF:
        return bytes([
            0xE0 | (code_point >> 12),
            0x80 | ((code_point >> 6) & 0x3F),
            0x80 | (code_point & 0x3F),
        ])
    return bytes([
        0xF0 | (code_point >> 18),
        0x80 | ((code_point >> 12) & 0x3F),
        0x80 | ((code_point >> 6) & 0x3F),
        0x80 | (code_point & 0x3F),
    ])


def cpp_string(value: str) -> str:
    """Emits a UTF-8 string literal using C++23 \\u{...} universal names."""
    escaped: list[str] = []
    for raw in value:
        code = ord(raw)
        if raw == "\\":
            escaped.append("\\\\")
        elif raw == '"':
            escaped.append('\\"')
        elif raw == "\n":
            escaped.append("\\n")
        elif raw == "\t":
            escaped.append("\\t")
        elif raw == "\r":
            escaped.append("\\r")
        elif code < 0x20 or code > 0x7E:
            escaped.append(f"\\u{{{code:x}}}")
        else:
            escaped.append(raw)
    return '"' + "".join(escaped) + '"'


def readable_name(tags: list[str], name: str, key: str) -> str:
    for tag in tags:
        cleaned = tag.strip(":").replace("-", " ").replace("_", " ").strip()
        if cleaned:
            return cleaned
    if name.startswith("emoji_u"):
        return name[len("emoji_u"):]
    return key


def main() -> int:
    manifest_path = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "ui/assets/emoji/noto_manifest.json"
    output_path = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "src/application/emoji/emoji_catalog_data.cpp"

    with open(manifest_path, encoding="utf-8") as handle:
        manifest = json.load(handle)

    entries = []
    for icon in manifest.get("icons", []):
        codepoint = str(icon.get("codepoint", ""))
        if not codepoint:
            continue
        raw_codes = [int(part, 16) for part in codepoint.split("_")]
        unicode_text = "".join(chr(code) for code in raw_codes).encode("utf-8", "surrogatepass").decode("utf-8")
        categories = icon.get("categories") or []
        upstream_category = categories[0] if categories else "Symbols"
        category = CATEGORY_MAP.get(upstream_category, "Symbols")
        tags = list(icon.get("tags") or [])
        name = readable_name(tags, str(icon.get("name", "")), codepoint)
        entries.append((unicode_text, codepoint, category, name, tags))

    entries.sort(key=lambda entry: (CATEGORY_ORDER.index(entry[2]), entry[1]))

    lines: list[str] = []
    lines.append("// Generated by tools/generate_emoji_catalog.py — do not edit by hand.")
    lines.append("// Source data: ui/assets/emoji/noto_manifest.json (Google Noto Animated Emoji,")
    lines.append("// CC BY 4.0). Unicode sequences are the canonical emoji text; keys are the")
    lines.append("// normalized Noto asset identifiers used for animation lookup only.")
    lines.append("module;")
    lines.append("")
    lines.append("#include <cstddef>")
    lines.append("#include <string_view>")
    lines.append("")
    lines.append("module farcaster.application.emoji.catalog;")
    lines.append("")
    lines.append("namespace farcaster::application::emoji::catalog {")
    lines.append("")
    lines.append("// Module-linkage raw table shared with the catalog implementation unit;")
    lines.append("// RawEntry is declared (not exported) in the module interface.")
    lines.append("constexpr RawEntry RawEntries[] = {")
    for unicode_text, codepoint, category, name, tags in entries:
        tags_text = " ".join(tag.strip(":") for tag in tags)
        lines.append(
            f"    {{ {cpp_string(unicode_text)}, {cpp_string(codepoint)}, "
            f"{cpp_string(category)}, {cpp_string(name)}, {cpp_string(tags_text)} }},"
        )
    lines.append("};")
    lines.append("")
    lines.append("")
    lines.append("std::size_t entryCount() noexcept")
    lines.append("{")
    lines.append("    return sizeof(RawEntries) / sizeof(RawEntries[0]);")
    lines.append("}")
    lines.append("")
    lines.append("const RawEntry& entryAt(const std::size_t index) noexcept")
    lines.append("{")
    lines.append("    return RawEntries[index];")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace farcaster::application::emoji::catalog")
    lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {output_path} with {len(entries)} entries.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())