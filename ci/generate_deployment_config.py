#!/usr/bin/env python3
"""Validate deployment origins before C++/QML/WASM code generation.

No shell interpolation, no executable text from deployment values, and no secrets.
Only HTTPS host origins (plus the explicitly scoped OAuth browser path) are
accepted. Emitted JS is JSON data, not interpolated JavaScript statements.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import ipaddress
import re
from urllib.parse import urlsplit

NAMES = {
    "GENYCASTER_PUBLIC_ORIGIN": "publicOrigin",
    "GENYCASTER_SIWF_ORIGIN": "siwfOrigin",
    "GENYCASTER_OPENPROOF_ISSUER": "openProofIssuer",
    "GENYCASTER_OPENPROOF_BROWSER_BASE": "openProofBrowserBase",
    "GENYCASTER_BROWSER_GATEWAY_ORIGIN": "browserGateway",
    "GENYCASTER_MEDIA_PUBLIC_ORIGIN": "mediaPublicOrigin",
    "GENYCASTER_SNAPCHAIN_ORIGIN": "snapchainOrigin",
    "GENYCASTER_HYPERSNAP_ORIGIN": "hypersnapOrigin",
    "GENYCASTER_COMPANY_ORIGIN": "companyOrigin",
}
HOST = re.compile(r"^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)*[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$")
PATHS = {"openProofBrowserBase": {"/openproof"}}


def normalize(value: str, key: str) -> str:
    if not isinstance(value, str) or not 8 <= len(value) <= 512:
        raise ValueError(f"{key}: invalid URL length")
    if any(ord(ch) < 33 or ord(ch) > 126 for ch in value) or any(
        ch in value for ch in ('\\\\', '"', "'", '`', '$', ';', '{', '}', '<', '>', '|')
    ):
        raise ValueError(f"{key}: URL contains forbidden characters")
    parsed = urlsplit(value)
    if parsed.scheme != "https" or not parsed.hostname or not HOST.fullmatch(parsed.hostname):
        raise ValueError(f"{key}: a credential-free HTTPS DNS hostname is required")
    if "." not in parsed.hostname:
        raise ValueError(f"{key}: DNS hostname is required")
    try:
        ipaddress.ip_address(parsed.hostname)
    except ValueError:
        pass
    else:
        raise ValueError(f"{key}: IP literals are forbidden")
    if parsed.username or parsed.password or parsed.port is not None or parsed.query or parsed.fragment:
        raise ValueError(f"{key}: credentials, port, query and fragment are forbidden")
    path = parsed.path.rstrip('/')
    if path not in PATHS.get(key, {""}):
        raise ValueError(f"{key}: unexpected URL path")
    if parsed.netloc != parsed.hostname:
        raise ValueError(f"{key}: noncanonical hostname")
    return "https://" + parsed.hostname + path


def write_changed(path: Path, data: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != data:
        path.write_text(data, encoding="utf-8")


def generate(values: dict[str, str], output: Path) -> dict[str, str]:
    missing = set(NAMES) - set(values)
    extras = set(values) - set(NAMES)
    if missing or extras:
        raise ValueError(f"Deployment keys: missing={sorted(missing)} unknown={sorted(extras)}")
    config = {destination: normalize(values[name], destination)
              for name, destination in NAMES.items()}
    if config["openProofIssuer"] == config["publicOrigin"]:
        raise ValueError("The account issuer must be isolated from the application origin")
    public = {
        "openproofProviderCatalogUrl": config["browserGateway"] + "/v1/browser/openproof/providers",
        "openproofIssuerUrl": config["openProofIssuer"],
        "openproofBrowserConnectionBaseUrl": config["openProofBrowserBase"],
        "openproofConnectionsGatewayUrl": config["browserGateway"] + "/v1/browser/openproof/connections",
        "genycasterCloudApiUrl": config["publicOrigin"] + "/api/v1/cloud/profile_extras",
        **config,
    }
    cpp = [
        "// GENERATED by ci/generate_deployment_config.py; do not edit.",
        "#pragma once",
        "#include <string_view>",
        "namespace genycaster::deployment {",
    ]
    for key, value in config.items():
        cpp.append("inline constexpr std::string_view " + key
                   + "{" + json.dumps(value, ensure_ascii=True) + "};")
    cpp.append("} // namespace genycaster::deployment")
    write_changed(output / "genycaster_deployment.hpp", "\n".join(cpp) + "\n")
    write_changed(output / "public_endpoints.json",
                  json.dumps(public, sort_keys=True, indent=2) + "\n")
    write_changed(output / "deployment_config.mjs",
                  "// GENERATED; public non-secret build configuration.\n"
                  + "export const deployment = Object.freeze("
                  + json.dumps(config, sort_keys=True, separators=(",", ":")) + ");\n")
    # Contains public service origins only. Credentials stay server-side.
    # Sanitized origin values are safe to source as environment assignments.
    server_env = {
        **{key: config[member] for key, member in NAMES.items()},
        "GENYCASTER_OPENPROOF_CONNECTION_BROWSER_BASE": config["openProofBrowserBase"],
        "GENYLEAP_MEDIA_PUBLIC_BASE_URL": config["mediaPublicOrigin"],
        "GENYLEAP_MEDIA_SNAPCHAIN_BASE_URL": config["snapchainOrigin"],
        "GENYCASTER_SNAPCHAIN_URL": config["snapchainOrigin"],
        "GENYCASTER_DEPLOYMENT_STRICT": "1",
    }
    write_changed(output / "deployment.env",
                  "# GENERATED PUBLIC ENDPOINTS ONLY; contains no secrets.\n"
                  + "".join(f"{key}={value}\n" for key, value in server_env.items()))
    return config


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--set", action="append", default=[])
    args = parser.parse_args()
    values: dict[str, str] = {}
    for assignment in args.set:
        key, sep, value = assignment.partition("=")
        if not sep or key in values:
            parser.error("Invalid or duplicated --set key")
        values[key] = value
    try:
        generate(values, args.out_dir)
    except (ValueError, OSError) as exc:
        parser.error(str(exc))


if __name__ == "__main__":
    main()
