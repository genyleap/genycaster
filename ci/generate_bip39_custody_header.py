#!/usr/bin/env python3
"""Reproduce the native BIP39 English table from the audited WASM vendor list."""
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parents[1]
js = (root / "ui/wasm/vendor/bip39-english.mjs").read_text(encoding="utf-8")
match = re.search(r'Object\.freeze\(`([a-z\n]+)`\.split\(\'\\n\'\)\)', js)
if match is None:
    sys.exit("Unexpected audited BIP39 vendor format")
words = match.group(1).splitlines()
if len(words) != 2048 or len(set(words)) != 2048 or words != sorted(words):
    sys.exit("BIP39 wordlist must contain 2,048 unique sorted English words")
header = root / "src/platform/custody_bip39_english.hpp"
header_documentation = '''/*!
 * @file        src/platform/custody_bip39_english.hpp
 * @brief       Generated BIP-39 English recovery dictionary.
 *
 * @details
 * Contains the public 2,048-word scure-bip39 list as compile-time data
 * for custody recovery, preserving upstream MIT attribution and the C/ABI
 * textual boundary.
 *
 * @author      GenyCaster contributors (binding); scure-bip39 contributors (wordlist).
 * @since       30 Oct 2026
 * @copyright   Copyright (c) 2026 Genyleap (generated binding only).
 * @license     Wordlist: MIT (ui/wasm/vendor/scure-bip39.LICENSE); binding: see LICENSE.
 */

'''
body = ('''// Generated by ci/generate_bip39_custody_header.py from the vendored
// scure-bip39 (MIT License) English wordlist. Textual C/ABI data boundary.
// Never modify the two copies
// independently. This is a public dictionary, not private key material.
#pragma once
#include <array>
#include <string_view>

namespace farcaster::platform::custody_recovery::detail {
inline constexpr std::array<std::string_view, 2048> englishWords{\n'''
        + ''.join('    "' + word + '",\n' for word in words)
        + '''};
} // namespace farcaster::platform::custody_recovery::detail
''')
body = header_documentation + body
if "--check" in sys.argv:
    if not header.exists() or header.read_text(encoding="utf-8") != body:
        sys.exit("Native BIP39 wordlist does not match the audited WASM vendor")
    print("Native BIP39 wordlist matches the audited English dictionary")
else:
    header.write_text(body, encoding="utf-8")
    print(f"Regenerated {header.name}: {len(words)} words")
